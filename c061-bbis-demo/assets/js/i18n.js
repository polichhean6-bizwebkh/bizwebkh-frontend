let currentLanguage = 'km';
// A fresh preference key makes this Khmer-first revision open correctly for earlier demo visitors.
const languageStorageKey = 'bbis-language-v2';
function translate(key) { return translations[currentLanguage][key] ?? translations.en[key] ?? ''; }
// Text and explicit line-break nodes only: translation values are never parsed as HTML.
function renderTranslation(element, value) {
  const fragment = document.createDocumentFragment();
  value.split('\n').forEach((line, index) => {
    if (index) fragment.append(document.createElement('br'));
    fragment.append(document.createTextNode(line));
  });
  element.replaceChildren(fragment);
}
function setLanguage(language, save = true) {
  currentLanguage = language === 'en' ? 'en' : 'km';
  document.documentElement.lang = currentLanguage;
  document.querySelectorAll('[data-i18n]').forEach(element => renderTranslation(element, translate(element.dataset.i18n)));
  for (const attribute of ['aria-label', 'alt', 'data-caption', 'content']) {
    document.querySelectorAll('[data-i18n-' + attribute + ']').forEach(element => element.setAttribute(attribute, translate(element.getAttribute('data-i18n-' + attribute))));
  }
  const menu = document.querySelector('.menu-toggle');
  menu.setAttribute('aria-label', translate(menu.getAttribute('aria-expanded') === 'true' ? 'menuClose' : 'menuOpen'));
  document.querySelectorAll('[data-language]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.language === currentLanguage)));
  const gallery = document.querySelector('[data-lightbox][data-active-preview]') || document.querySelector('[data-lightbox]');
  const dialog = document.querySelector('#lightbox');
  dialog.querySelector('p').textContent = gallery.dataset.caption;
  dialog.querySelector('img').alt = gallery.dataset.caption;
  if (save) { try { localStorage.setItem(languageStorageKey, currentLanguage); } catch { /* Switching still works when storage is unavailable. */ } }
  document.dispatchEvent(new Event('bbis:languagechange'));
}
document.querySelectorAll('[data-language]').forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.language)));
let savedLanguage = 'km';
try { savedLanguage = localStorage.getItem(languageStorageKey) || 'km'; } catch { /* Default to Khmer. */ }
setLanguage(savedLanguage, false);
