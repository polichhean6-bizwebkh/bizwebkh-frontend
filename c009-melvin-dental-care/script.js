function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === "kh" ? "km" : lang === "cn" ? "zh" : "en";
  translatable.forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[lang][key]) node.textContent = translations[lang][key];
  });
  placeholderNodes.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (translations[lang][key]) node.placeholder = translations[lang][key];
  });
  langButtons.forEach((button) => button.classList.toggle("active", button.dataset.lang === lang));
  if (result.dataset.messageKey) result.textContent = translations[lang][result.dataset.messageKey];
}

function setFormResult(key) {
  result.dataset.messageKey = key;
  result.textContent = translations[currentLang][key];
}

function getStoredTheme() {
  try {
    return localStorage.getItem("melvin-theme");
  } catch (error) {
    return null;
  }
}

function saveTheme(theme) {
  try {
    localStorage.setItem("melvin-theme", theme);
  } catch (error) {
    // Theme still applies for the current page if storage is unavailable.
  }
}

function setTheme(theme) {
  const isDark = theme === "dark";
  document.documentElement.dataset.theme = isDark ? "dark" : "light";
  saveTheme(isDark ? "dark" : "light");
  themeToggle.setAttribute("aria-pressed", String(isDark));
  themeToggle.setAttribute("aria-label", isDark ? "Switch to light mode" : "Switch to dark mode");
  themeIcon.textContent = isDark ? "\u2600" : "\u263e";
  themeText.textContent = isDark ? "Light" : "Dark";
}

