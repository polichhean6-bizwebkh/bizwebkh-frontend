const LANG_KEY = "c043_lang";
function getLang(){ return localStorage.getItem(LANG_KEY) || "km"; }
function setLang(l){
  localStorage.setItem(LANG_KEY, l);
  applyI18n();
  // fired once per explicit language switch - pages listen to this to re-render
  // dynamic (data-driven) content such as product grids and tables.
  document.dispatchEvent(new CustomEvent("langchanged"));
}
function t(key){ const l = getLang(); return (I18N[l] && I18N[l][key]) || I18N.km[key] || key; }

function applyI18n(){
  const l = getLang();
  document.documentElement.setAttribute("lang", l);
  document.body.classList.toggle("lang-km", l === "km");
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.getAttribute("data-i18n");
    if (I18N[l] && I18N[l][key] !== undefined) el.textContent = I18N[l][key];
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el=>{
    const key = el.getAttribute("data-i18n-ph");
    if (I18N[l] && I18N[l][key] !== undefined) el.setAttribute("placeholder", I18N[l][key]);
  });
  document.querySelectorAll(".lang-switch button").forEach(b=>{
    b.classList.toggle("active", b.dataset.lang === l);
  });
}
document.addEventListener("DOMContentLoaded", applyI18n);
