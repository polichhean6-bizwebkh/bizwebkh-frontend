function buildAppointmentMessage(formData) {
  return `Hello Melvin Dental Care,
I would like to request an appointment.

Name: ${formData.name}
Phone: ${formData.phone}
Service: ${formData.service}
Preferred Date: ${formData.date}
Preferred Time: ${formData.time}
Message: ${formData.message || "-"}

Thank you.`;
}

async function copyAppointmentMessage(message) {
  try {
    await navigator.clipboard.writeText(message);
    setFormResult("telegramCopied");
  } catch (error) {
    setFormResult("formThanks");
  }
}

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  const formData = {
    name: form.elements.name.value.trim(),
    phone: form.elements.phone.value.trim(),
    service: form.elements.service.value.trim(),
    date: form.elements.date.value.trim(),
    time: form.elements.time.value.trim(),
    message: form.elements.message.value.trim()
  };
  const requiredField = ["name", "phone", "service", "date", "time"].find((key) => !formData[key]);
  if (requiredField) {
    setFormResult("validationRequired");
    form.elements[requiredField].focus();
    return;
  }

  const appointmentMessage = buildAppointmentMessage(formData);
  const telegramUrl = `${MELVIN_TELEGRAM_LINK}?text=${encodeURIComponent(appointmentMessage)}`;
  const opened = window.open(telegramUrl, "_blank", "noopener");
  if (opened) {
    setFormResult("telegramOpened");
  } else {
    await copyAppointmentMessage(appointmentMessage);
  }
});

